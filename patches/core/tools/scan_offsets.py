"""Resolve and regenerate the three core-owned shared signatures.

The signature source is patches/core/signatures.ini.  Unlike feature scanners,
the core does not write offsets_cache.ini: runtime resolution always goes
through the retained pristine-image service.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "common"))
from paths import PROJ, add_game_root_arg, game_root  # noqa: E402
from peutil import load_pe  # noqa: E402
sys.path.insert(0, str(PROJ / "patches" / "chatmod" / "tools"))
import scan_offsets as shared  # noqa: E402

ROOT = PROJ / "patches" / "core"
PREFIX = "Core_"


def read_signatures(path: Path) -> dict[str, dict[str, str]]:
    result: dict[str, dict[str, str]] = {}
    section: str | None = None
    for raw_line in path.read_text(encoding="utf-8-sig").splitlines():
        line = raw_line.strip()
        if not line or line.startswith(";"):
            continue
        if line.startswith("[") and line.endswith("]"):
            section = line[1:-1]
            result[section] = {}
        elif section is not None and "=" in line:
            key, value = line.split("=", 1)
            result[section][key.strip()] = value.strip()
    return result


def format_bytes(raw: bytes) -> str:
    rows = []
    for offset in range(0, len(raw), 8):
        rows.append("    " + ", ".join(
            "0x%02X" % value for value in raw[offset:offset + 8]))
    return ",\n".join(rows)


def generate(pe, signatures, resolved) -> str:
    blobs: list[str] = []
    rows: list[str] = []
    for full_name, body in signatures.items():
        if not full_name.startswith(PREFIX):
            continue
        short = full_name[len(PREFIX):]
        raw, mask = shared.parse_pattern(body["sig"])
        variable = "osmw_sig_" + short.lower()
        blobs.append("static const BYTE %s[] = {\n%s\n};" %
                     (variable, format_bytes(raw)))
        rows.append(
            '    {"%s", %s, "%s", %d, -1, 0x%08Xu, %d}' %
            (short, variable, "".join("x" if bit else "?" for bit in mask),
             len(raw), resolved[full_name], int(body["hookLength"])))
    return """/* GENERATED by patches/core/tools/scan_offsets.py -- do not edit by hand.
 * Source of truth: patches/core/signatures.ini (Core_* sections).
 * Reference build: main.exe timestamp 0x%08X
 */
#ifndef OSMW_CORE_SIGS_H
#define OSMW_CORE_SIGS_H

typedef struct OSMW_CORE_SIGNATURE_DEF {
    const char *name;
    const BYTE *pattern;
    const char *mask;
    DWORD length;
    LONG operand_offset;
    DWORD reference_rva;
    DWORD hook_length;
} OSMW_CORE_SIGNATURE_DEF;

%s

static const OSMW_CORE_SIGNATURE_DEF OSMW_CORE_SIGNATURES[] = {
%s
};

#define OSMW_CORE_SIGNATURE_COUNT \\
    ((DWORD)(sizeof(OSMW_CORE_SIGNATURES) / sizeof(OSMW_CORE_SIGNATURES[0])))

#endif /* OSMW_CORE_SIGS_H */
""" % (pe.timestamp, "\n".join(blobs), ",\n".join(rows))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true",
                        help="regenerate src/sigs.h after a clean scan")
    add_game_root_arg(parser)
    args = parser.parse_args()

    pe = load_pe(game_root(args.game_root) / "main.exe")
    signatures = read_signatures(ROOT / "signatures.ini")
    ours = {name: body for name, body in signatures.items()
            if name.startswith(PREFIX)}
    shared.PREFIX = PREFIX
    resolved, problems = shared.scan(pe, signatures)
    print("main.exe build 0x%08X  (%d core signatures)  rva / va" %
          (pe.timestamp, len(ours)))
    for name in ours:
        if name in resolved:
            print("  OK   %-24s 0x%08X / 0x%08X" %
                  (name, resolved[name], resolved[name] + pe.image_base))
        else:
            print("  FAIL %-24s" % name)
    for problem in problems:
        print("  !! %s" % problem)
    if len(resolved) != len(ours):
        print("\nnot writing: every core signature must resolve exactly once")
        return 1
    if not args.write:
        print("\n(dry run -- pass --write to regenerate src/sigs.h)")
        return 0
    output = ROOT / "src" / "sigs.h"
    output.write_text(generate(pe, signatures, resolved), encoding="ascii")
    print("\nwrote %s" % output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
