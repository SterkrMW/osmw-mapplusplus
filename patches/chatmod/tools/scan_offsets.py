"""Resolve the ChatMod_* signatures against main.exe.

Reads the patterns from the project's signatures.ini (the single source of truth),
scans main.exe's .text for exactly one match each, refreshes offsets_cache.ini for
this build, and regenerates src/sigs.h so the DLL scans with the same patterns.

    python patches/chatmod/tools/scan_offsets.py            # scan + report
    python patches/chatmod/tools/scan_offsets.py --write    # also update ini + sigs.h
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "common"))
from paths import PROJ, add_game_root_arg, game_root  # noqa: E402
from peutil import load_pe, off_to_va  # noqa: E402

PREFIX = "ChatMod_"


def read_signatures(path: Path) -> dict[str, dict[str, str]]:
    """Parse signatures.ini (UTF-16 with BOM) into {section: {key: value}}."""
    text = path.read_text(encoding="utf-16")
    out: dict[str, dict[str, str]] = {}
    section = None
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith(";"):
            continue
        if line.startswith("[") and line.endswith("]"):
            section = line[1:-1]
            out[section] = {}
        elif section and "=" in line:
            k, v = line.split("=", 1)
            out[section][k.strip()] = v.strip()
    return out


def parse_pattern(sig: str) -> tuple[bytes, list[int]]:
    """'AB ?? CD' -> (b'\\xab\\x00\\xcd', [1, 0, 1])."""
    raw, mask = bytearray(), []
    for tok in sig.split():
        if tok == "??":
            raw.append(0)
            mask.append(0)
        else:
            raw.append(int(tok, 16))
            mask.append(1)
    return bytes(raw), mask


def find_all(data: bytes, raw: bytes, mask: list[int], lo: int, hi: int) -> list[int]:
    """Every wildcard match of raw/mask in data[lo:hi], anchored on the first fixed byte."""
    fixed = [i for i in range(len(raw)) if mask[i]]
    if not fixed:
        raise ValueError("pattern is entirely wildcards")
    anchor = fixed[0]
    needle = bytes([raw[anchor]])
    hits, pos = [], lo + anchor
    end = hi - len(raw) + anchor
    while True:
        i = data.find(needle, pos, end)
        if i < 0:
            return hits
        start = i - anchor
        if start >= lo and all(data[start + k] == raw[k] for k in fixed):
            hits.append(start)
        pos = i + 1


def scan(pe, sigs: dict[str, dict[str, str]]) -> tuple[dict[str, int], list[str]]:
    data = bytes(pe.data)
    text = next(s for s in pe.sections if s.name == ".text")
    lo, hi = text.raw, text.raw + text.rsize

    resolved: dict[str, int] = {}
    problems: list[str] = []
    for name, body in sigs.items():
        if not name.startswith(PREFIX) or "sig" not in body:
            continue
        raw, mask = parse_pattern(body["sig"])
        hits = find_all(data, raw, mask, lo, hi)
        if len(hits) != 1:
            problems.append("%s: %d matches (need exactly 1)" % (name, len(hits)))
            continue
        off = hits[0]
        if "opOffset" in body:
            # the pattern points at an instruction; the value we want is the
            # absolute address encoded at opOffset bytes into it
            op = int(body["opOffset"])
            value = struct.unpack_from("<I", data, off + op)[0]
        else:
            value = off_to_va(pe, off)
        # store RVAs, matching the convention the rest of offsets_cache.ini uses
        resolved[name] = value - pe.image_base
    return resolved, problems


HEADER_TEMPLATE = """\
/* GENERATED by patches/chatmod/tools/scan_offsets.py -- do not edit by hand.
 * Source of truth: signatures.ini (ChatMod_* sections).
 * Reference build: main.exe timestamp 0x{ts:08X}
 */
#ifndef OSMW_SIGS_H
#define OSMW_SIGS_H

typedef struct {{
    const char    *name;
    const unsigned char *pattern;  /* wildcard bytes are 0 */
    const char    *mask;           /* 'x' = must match, '?' = any */
    int            length;
    int            op_offset;      /* >=0: read an absolute address at this offset */
    unsigned int   reference_rva;  /* what it resolved to on the reference build */
    int            optional;       /* 1 = miss does not stand down the mod */
}} mw_sig_t;

{blobs}
static const mw_sig_t MW_SIGS[] = {{
{rows}}};

#define MW_SIG_COUNT ((int)(sizeof(MW_SIGS) / sizeof(MW_SIGS[0])))

/* Index into MW_SIGS / mw_addr[], in declaration order. */
enum {{
{enums}    MW_ADDR_COUNT
}};

#endif /* OSMW_SIGS_H */
"""


def generate_header(pe, sigs, resolved) -> str:
    blobs, rows, enums = [], [], []
    for name, body in sigs.items():
        if not name.startswith(PREFIX) or "sig" not in body:
            continue
        raw, mask = parse_pattern(body["sig"])
        short = name[len(PREFIX):]
        var = "sig_" + short.lower()
        blobs.append("static const unsigned char %s[] = {%s};"
                     % (var, ", ".join("0x%02X" % b for b in raw)))
        optional = 0 if body.get("optional", "0") in ("0", "", "false") else 1
        rows.append('    {"%s", %s, "%s", %d, %d, 0x%08XU, %d},'
                    % (short, var, "".join("x" if m else "?" for m in mask),
                       len(raw), int(body.get("opOffset", -1)),
                       resolved.get(name, 0), optional))
        enums.append("    MW_%s," % short.upper())
    return HEADER_TEMPLATE.format(
        ts=pe.timestamp,
        blobs="\n".join(blobs),
        rows="\n".join(rows) + "\n",
        enums="\n".join(enums) + "\n",
    )


def update_offsets_cache(path: Path, build: str, resolved: dict[str, int]) -> None:
    """Merge our keys into the [Build_XXXXXXXX] section, preserving everything else."""
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    target = "[Build_%s]" % build
    ours = {name[len(PREFIX):]: va for name, va in resolved.items()}

    out, i, wrote = [], 0, False
    while i < len(lines):
        line = lines[i]
        out.append(line)
        if line.strip() == target:
            i += 1
            # copy the section, dropping any stale ChatMod keys
            while i < len(lines) and not lines[i].strip().startswith("["):
                key = lines[i].split("=", 1)[0].strip()
                if key not in ours:
                    out.append(lines[i])
                i += 1
            for k in sorted(ours):
                out.append("%s=0x%08X" % (k, ours[k]))
            wrote = True
            continue
        i += 1

    if not wrote:
        out.append(target)
        for k in sorted(ours):
            out.append("%s=0x%08X" % (k, ours[k]))
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true",
                    help="update offsets_cache.ini and regenerate src/sigs.h")
    add_game_root_arg(ap)
    args = ap.parse_args()

    game = game_root(getattr(args, "game_root", None))
    pe = load_pe(game / "main.exe")
    sigs = read_signatures(game / "signatures.ini")
    ours = {k: v for k, v in sigs.items() if k.startswith(PREFIX)}
    if not ours:
        print("no %s* sections in signatures.ini" % PREFIX)
        return 1

    resolved, problems = scan(pe, sigs)
    print("main.exe build 0x%08X  (%d %s signatures)  rva / va"
          % (pe.timestamp, len(ours), PREFIX))
    for name in ours:
        if name in resolved:
            print("  OK   %-28s 0x%08X / 0x%08X"
                  % (name, resolved[name], resolved[name] + pe.image_base))
        else:
            print("  FAIL %-28s" % name)
    for p in problems:
        print("  !! %s" % p)
    if problems:
        return 1

    if args.write:
        update_offsets_cache(game / "offsets_cache.ini", "%08X" % pe.timestamp, resolved)
        header = PROJ / "patches" / "chatmod" / "src" / "sigs.h"
        header.write_text(generate_header(pe, ours, resolved), encoding="utf-8")
        print("\nwrote offsets_cache.ini and %s" % header.relative_to(PROJ))
    else:
        print("\n(dry run -- pass --write to update offsets_cache.ini and sigs.h)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
